// ---- 搜索城市（离线，大小写不敏感模糊匹配） ----
function searchCities(query) {
    var q = query.trim().toLowerCase();
    if (!q) return [];
    var results = [];
    for (var i = 0; i < CITY_DB.length; i++) {
        if (CITY_DB[i][0].toLowerCase().indexOf(q) !== -1) {
            results.push(CITY_DB[i][0]);
        }
    }
    // 去重保持顺序
    var seen = {};
    var unique = [];
    for (var j = 0; j < results.length; j++) {
        if (!seen[results[j]]) {
            seen[results[j]] = true;
            unique.push(results[j]);
        }
    }
    return unique;
}

