// 坐标 → 最近城市名（离线，0 网络请求）
function findNearestCity(lat, lon) {
    var bestCity = null;
    var bestDist = Infinity;
    for (var i = 0; i < CITY_DB.length; i++) {
        var cLat = CITY_DB[i][1];
        var cLon = CITY_DB[i][2];
        // 用简化的距离公式（等矩形投影）
        var dLat = (lat - cLat) * 111;       // 1° ≈ 111km
        var dLon = (lon - cLon) * 111 * Math.cos(lat * Math.PI / 180);
        var dist = Math.sqrt(dLat * dLat + dLon * dLon);
        if (dist < bestDist) {
            bestDist = dist;
            bestCity = CITY_DB[i][0];
        }
    }
    // 距离超过 150km 说明不在已知城市范围内
    return bestDist < 150 ? bestCity : null;
}

